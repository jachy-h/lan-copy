const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = {window: {}, Set, Error, Promise};
vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname, '../web/upload-tree.js'), 'utf8'), context);
const {fromEntries, fromFiles} = context.window.LanCopyUploadTree;
const file = name => ({name, isFile:true, isDirectory:false, file(resolve) { queueMicrotask(() => resolve({name})); }});
const directory = (name, children) => ({name, isFile:false, isDirectory:true, createReader() { let index=0; return {readEntries(resolve) { const batch=children.slice(index,index+100);index+=100;queueMicrotask(() => resolve(batch)); }}; }});
(async () => {
  const children = Array.from({length:205}, (_, index) => file(`${index}.txt`));
  children.push(directory('empty', []), directory('nested', [file('same.txt')]));
  const entries = await fromEntries([directory('照片', children), file('loose.txt')]);
  assert.equal(entries.filter(entry => !entry.directory).length,207);
  assert(entries.some(entry => entry.path === '照片/empty' && entry.directory));
  assert(entries.some(entry => entry.path === '照片/204.txt'));
  assert(entries.some(entry => entry.path === '照片/nested/same.txt'));
  assert(entries.some(entry => entry.path === 'loose.txt'));
  const selected = fromFiles([{name:'a.txt',webkitRelativePath:'folder/sub/a.txt'}, {name:'b.txt',webkitRelativePath:'folder/sub/b.txt'}], true);
  assert.equal(selected.filter(entry => entry.directory).length,2);
  assert.equal(selected.filter(entry => !entry.directory).length,2);
  assert.throws(() => fromFiles([{name:'a.txt'}],true), /未提供文件夹路径/);
  assert.throws(() => fromFiles(Array.from({length:10001},(_,i)=>({name:`${i}.txt` }))), /10000/);
  await assert.rejects(fromEntries([{name:'denied',isFile:true,file(resolve,reject){reject(new Error('permission denied'));}}]), /permission denied/);
  let deep=file('file.txt');for(let i=0;i<65;i++)deep=directory('sub',[deep]);
  await assert.rejects(fromEntries([deep]), /64/);
  console.log('Folder collection checks passed: >100 entries, nesting, empty folders, picker paths, limits and read errors.');
})().catch(error => {console.error(error);process.exitCode=1;});
